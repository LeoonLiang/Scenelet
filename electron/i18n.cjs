// Same rule as src/i18n: the first Chinese or English entry wins, anything else falls back to English.
function resolve(preferred = []) {
  for (const tag of preferred) {
    const lower = String(tag).toLowerCase();
    if (lower.startsWith('zh')) return 'zh';
    if (lower.startsWith('en')) return 'en';
  }
  return 'en';
}
// Defaults to Chinese until main.cjs applies the user's choice; unit tests rely on this default.
let current = 'zh';
function setLanguage(lang) { if (messages[lang]) current = lang; return current; }
function language() { return current; }
function t(key, vars = {}) {
  const text = messages[current][key] ?? messages.zh[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => name in vars ? String(vars[name]) : match);
}
module.exports = { messages, resolve, setLanguage, language, t };
